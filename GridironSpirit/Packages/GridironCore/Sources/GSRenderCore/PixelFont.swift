import GSFoundation

/// Chunky 5x7 bitmap font (6 px advance, 8 px line). Original glyph set.
/// Lowercase input is drawn uppercase.
public enum PixelFont {
    public static let glyphWidth = 5
    public static let glyphHeight = 7
    public static let advance = 6
    public static let lineHeight = 8

    public static func width(of text: String) -> Int {
        text.isEmpty ? 0 : text.count * advance - 1
    }

    public static func glyph(_ ch: Character) -> [String]? {
        glyphs[Character(ch.uppercased())]
    }

    /// True if glyph pixel (col, row) is set; unknown characters draw as "?".
    public static func bit(_ ch: Character, _ col: Int, _ row: Int) -> Bool {
        guard col >= 0, col < glyphWidth, row >= 0, row < glyphHeight else { return false }
        guard let g = glyph(ch) ?? glyphs["?"] else { return false }
        let line = g[row]
        return line[line.index(line.startIndex, offsetBy: col)] == "#"
    }

    /// Precomputed digit bitmaps (bit 4 = leftmost column) for hot loops.
    static let digitMasks: [[UInt8]] = (0...9).map { d in
        glyphs[Character(String(d))]!.map { line in
            line.reduce(UInt8(0)) { ($0 << 1) | ($1 == "#" ? 1 : 0) }
        }
    }

    @inline(__always)
    public static func digitBit(_ digit: Int, _ col: Int, _ row: Int) -> Bool {
        guard digit >= 0, digit <= 9, col >= 0, col < glyphWidth, row >= 0, row < glyphHeight else { return false }
        return (digitMasks[digit][row] >> UInt8(glyphWidth - 1 - col)) & 1 == 1
    }

    public static func draw(_ text: String, into buf: inout PixelBuffer, x: Int, y: Int, _ c: RGBA) {
        var cx = x
        for ch in text {
            if ch != " " {
                for row in 0..<glyphHeight {
                    for col in 0..<glyphWidth where bit(ch, col, row) {
                        buf.set(cx + col, y + row, c)
                    }
                }
            }
            cx += advance
        }
    }

